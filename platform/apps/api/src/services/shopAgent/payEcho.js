'use strict';
/**
 * payEcho.js — прибирає з відповіді моделі перелік способів оплати, коли його далі додає система (2.11.2026).
 *
 * Правка Олексія «Двічі пише про способи оплати» (yuragolubosh, 01.11): на питання про блискавку модель (compose) відповіла й сама
 * дописала «Графітовий XL вже підібрано, лишилось обрати спосіб оплати — оберіть зручний варіант: 1️⃣ … 2️⃣ …», а слідом політика додала
 * свій шаблон «Готово, лишилось обрати оплату! 1️⃣ … 2️⃣ … Напишіть 1 або 2». Інструкція моделі («сам список дасть система») не
 * виконується надійно, тому тут детермінований запобіжник: речення, де модель сама перелічує способи оплати чи закликає їх обрати, —
 * прибираємо, лишаємо відповідь по суті.
 */
const OPTION_WORDS = /1️⃣|2️⃣|(?:^|\s)[12][.)]\s|спосіб оплати|способи оплати|способів оплати|обер(?:іть|ете)\s+(?:зручн|оплат|спосіб)|лишилось\s+обрати\s+(?:оплат|спосіб)|напишіть\s+1\s+або\s+2/i;

/** Речення: після . ! ? … або емодзі; нумерований перелік (1️⃣ … 2️⃣ …) лишається в тому реченні, де почався. */
function sentences(text) {
    return String(text || '').split(/(?<=[.!?…])\s+|(?<=\p{Extended_Pictographic})\s+(?!\p{Extended_Pictographic}|[12]️?⃣)/u).map((s) => s.trim()).filter(Boolean);
}

/** Відповідь без речень про вибір способу оплати. Нічого не лишилось — повертає '' (виклик сам вирішує, що робити). */
function dropPayOptionsEcho(text) {
    const t = String(text || '').trim();
    if (!t || !OPTION_WORDS.test(t)) return t;
    return sentences(t).filter((s) => !OPTION_WORDS.test(s)).join(' ').trim();
}

module.exports = { dropPayOptionsEcho, OPTION_WORDS };
