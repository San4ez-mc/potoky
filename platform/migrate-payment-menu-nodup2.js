// Продовження migrate-payment-flow-fixes.js: живий тест (P1) показав ДВІ речі:
// 1) не лише n_order_intent може продублювати меню оплати — n_set_choice і n_color
//    ТЕЖ мають useKb:true (той самий FAQ з деталями комісії).
// 2) слабка негативна інструкція ("не показуй нумероване меню 1️⃣/2️⃣") НЕ спрацювала
//    надійно — модель просто прибрала емодзі, але лишила той самий пронумерований
//    список з комісією (pink elephant ефект, той самий що і в n_unknown_msg раніше
//    в цій сесії). Замінено на СУВОРО шаблоновану фразу — той самий підхід, що
//    спрацював для n_unknown_msg (мінімум вільного міркування моделі).
const { PrismaClient } = require('@prisma/client');
const db = new PrismaClient();
const BOT = 'cc03657f-9e72-46e5-a16d-88826e70c2ee';
const APPLY = process.argv.includes('--apply');
const NL = String.fromCharCode(10);

const MARKER = 'НІКОЛИ не показуй нумероване меню';
// Старі (слабкі) варіанти інструкції, застосовані раніше — видаляємо їх перед вставкою нової.
const OLD_VARIANTS = [
  NL + 'Якщо клієнт питає про СПОСІБ оплати (передоплата/накладений/скільки зараз платити) — відповідай КОРОТКО одним реченням (напр. "можна частково зараз, решту при отриманні, або повністю одразу — на наступному кроці зручно оберете"). НІКОЛИ не показуй нумероване меню 1️⃣/2️⃣ з цифрами — це окремий наступний крок (n_pay), він формально запитає раз; якщо ти покажеш те саме меню зараз, клієнт відповість тобі, а потім йому доведеться відповідати ще раз.',
  NL + 'Якщо клієнт питає про СПОСІБ оплати (передоплата/накладений/скільки зараз платити) — відповідай КОРОТКО одним реченням (напр. "можна частково зараз, решту при отриманні, або повністю одразу — на наступному кроці зручно оберете"). НІКОЛИ не показуй нумероване меню 1️⃣/2️⃣ з цифрами — це окремий наступний крок (n_pay), він формально запитає раз; якщо ти покажеш те саме меню зараз, клієнту доведеться відповідати двічі.',
];
const NEW_ADDITION = NL + 'Якщо клієнт питає про СПОСІБ оплати (передоплата/накладений/скільки зараз платити/"як платити") — відповідай РІВНО одним реченням, БЕЗ списку, БЕЗ цифр 1/2, БЕЗ суми комісії: «Оплата гнучка — можна частину зараз і решту при отриманні, або одразу повністю; на наступному кроці зручно оберете 🙂». Саме такою фразою (можеш трохи адаптувати тон, але без списку/цифр/деталей). Деталі (суми, комісію, конкретний вибір) дає ВИКЛЮЧНО наступний крок (n_pay) — якщо повторити їх зараз, клієнту доведеться відповідати на той самий вибір двічі.';

(async () => {
  const fd = await db.flowDefinition.findUnique({ where: { botId: BOT } });
  const nodes = JSON.parse(JSON.stringify(fd.nodes));
  for (const id of ['n_order_intent', 'n_set_choice', 'n_color']) {
    const n = nodes.find((x) => x.id === id);
    if (!n) { console.log('❌ ' + id + ' NOT FOUND'); continue; }
    let sp = String(n.data.systemPrompt || '');
    let changed = false;
    for (const old of OLD_VARIANTS) {
      if (sp.includes(old)) { sp = sp.replace(old, ''); changed = true; }
    }
    if (sp.includes(MARKER)) {
      // якийсь варіант маркера лишився (не збігся дослівно) — прибираємо решту вручну неможливо,
      // тому просто перевіримо ще раз: якщо після заміни маркер зник — ставимо нову; інакше пропускаємо.
      console.log('⚠️ ' + id + ': старий маркер лишився після заміни, перевір вручну');
      continue;
    }
    n.data.systemPrompt = sp + NEW_ADDITION;
    console.log('✅ ' + id + (changed ? ': замінено слабку інструкцію на шаблоновану' : ': додано шаблоновану інструкцію'));
  }

  if (!APPLY) { console.log('\nDRY-RUN — запусти з --apply'); process.exit(0); }
  require('fs').writeFileSync('_backup_paymenu2_' + Date.now() + '.json', JSON.stringify({ nodes: fd.nodes }, null, 2));
  await db.flowDefinition.update({ where: { botId: BOT }, data: { nodes } });
  console.log('\n✅ записано');
  await db.$disconnect();
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
