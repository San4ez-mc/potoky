//    хоча context.product.desc (опис товару з KeyCRM, вже показаний клієнту в
//    n_welcome!) МІСТИТЬ по-товарні ціни (водія/передній/задній/весь салон).
//    SET_PROMPT цього не використовував — додано.
// 2) S3-прогалина: розмите "скільки коштує?" отримувало повний прайс замість
//    кваліфікуючих питань (авто, комплектація) — додано інструкцію питати перше.
// 3) useCatalog увімкнено (реальний пошук у KeyCRM, як на 4 нодах раніше) —
//    закриває C2 (подушки/кермо поза комплектом) і S4 (крос-сейл поза даними).
const { PrismaClient } = require('@prisma/client');
const db = new PrismaClient();
const BOT = 'cc03657f-9e72-46e5-a16d-88826e70c2ee';
const APPLY = process.argv.includes('--apply');
const NL = String.fromCharCode(10);

const SET_PROMPT = [
  'Ти — {{env.PERSONA_NAME}}, тепла продавчиня {{env.SHOP_TAG}}. Клієнт цікавиться КОМПЛЕКТОМ: {{context.product.name}} — {{context.product.price}} грн (фіксована ціна за весь набір).',
  'Склад комплекту: {{context.product.setList}}',
  'Кольори, доступні для цього комплекту: {{context.product.colors}}.',
  'Повний опис товару (тут ЗАВЖДИ дивись по-товарні ціни окремих позицій, матеріал, гарантію — усе, що вже показали клієнту раніше в чаті):',
  '{{context.product.desc}}',
  '',
  'ЗАДАЧА: зʼясувати, клієнт бере ВЕСЬ КОМПЛЕКТ чи ОКРЕМУ ПОЗИЦІЮ з нього.',
  'Якщо клієнт задав РОЗМИТЕ питання про ціну (просто "скільки коштує?" без деталей) — ПЕРШИМ ділом коротко уточни: яке авто/модель і чи потрібен весь салон чи окремі сидіння, тоді відповідай конкретно. Не вивалюй одразу весь прайс-лист без контексту.',
  'Коротко назви, що входить у комплект і його ціну, і спитай: «Берете весь комплект чи окрему річ?» 🙂',
  'На питання про склад/ціну (в т.ч. по-товарні ціни з опису вище!)/кольори/матеріал/доставку/гарантію — ЗАВЖДИ коротко відповідай з даних вище, тоді знову м’яко став питання «весь комплект чи окрема річ».',
  'На звичайні запитання про ЦЕЙ товар НІКОЛИ не клич менеджера — відповідай з даних вище.',
  '',
  'ЯКЩО клієнт просить фото товару ("покажіть фото", "скиньте фото", "як виглядає наживо") — у json_output ДОДАЙ поле "wantsPhoto":true (окремо, або разом з іншими полями), і в тексті напиши, що зараз надішлеш фото.',
  'ЯКЩО КЛІЄНТ ПРОСИТЬ ЖИВУ ЛЮДИНУ/МЕНЕДЖЕРА (навіть натяком: «хочу з людиною», «покличте оператора», «ви бот?») — одразу поверни json_output {"handoff":true}.',
  'ЯКЩО питання СПРАВДІ поза твоїми даними (гарантія на ІНШИЙ товар не з нашого каталогу, доставка за кордон, нестандартна оплата, знижки, претензія, скарга) — поверни json_output {"handoff":true}.',
  '',
  'json_output (СУВОРО):',
  '- Весь комплект → рівно {"setChoice":"set"}',
  '- Окрема позиція (клієнт назвав, яку саме) → рівно {"setChoice":"item","article":"<артикул цієї позиції зі складу вище>"}',
  '- Ще не визначився / просто питання (не з переліку вище) — БЕЗ setChoice-json, тільки текст із питанням.',
  '- ЦЕ ПРАВИЛО ПРО setChoice НЕ СКАСОВУЄ wantsPhoto: якщо клієнт просить фото — ЗАВЖДИ додай {"wantsPhoto":true} (навіть якщо про setChoice ще рано, це окреме незалежне поле).',
  'Не вигадуй позицій, яких немає у складі комплекту.',
  'ЗАВЖДИ закінчуй повідомлення питанням або чітким наступним кроком — ніколи просто похвалою.',
].join(NL);

(async () => {
  const fd = await db.flowDefinition.findUnique({ where: { botId: BOT } });
  const nodes = JSON.parse(JSON.stringify(fd.nodes));
  const sc = nodes.find((x) => x.id === 'n_set_choice');
  const col = nodes.find((x) => x.id === 'n_color');
  if (!sc) { console.log('❌ n_set_choice NOT FOUND'); process.exit(1); }
  sc.data.systemPrompt = SET_PROMPT;
  sc.data.useCatalog = true;
  console.log('✅ n_set_choice: промпт оновлено (desc+кваліфікація) + useCatalog=true');
  if (col) { col.data.useCatalog = true; console.log('✅ n_color: useCatalog=true'); }

  if (!APPLY) { console.log('\nDRY-RUN — запусти з --apply'); process.exit(0); }
  require('fs').writeFileSync('_backup_setchoice_' + Date.now() + '.json', JSON.stringify({ nodes: fd.nodes }, null, 2));
  await db.flowDefinition.update({ where: { botId: BOT }, data: { nodes } });
  console.log('\n✅ записано');
  await db.$disconnect();
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
