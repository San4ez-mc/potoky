'use strict';
// Прибирання markdown-зірочок у повідомленнях бота (скарга маркетолога): слова лишаються, код не чіпаємо.
const { convertCodeFencesToHtml: c } = require('../../apps/api/src/services/platformBotHandler');
let pass = 0, fail = 0;
const ok = (v, m) => { if (v) { pass++; console.log('  ✔ ' + m); } else { fail++; console.log('  ✘ ПРОВАЛ: ' + m); } };
ok(c('Це **важливо** і **ще це**') === 'Це важливо і ще це', 'жирний прибрано');
ok(c('### Заголовок\nтекст') === 'Заголовок\nтекст', 'заголовок без решіток');
ok(c('* пункт\n* інший') === '• пункт\n• інший', 'зірочкові списки → крапки');
ok(c('Ціна 2*3 і 5 * 4') === 'Ціна 2*3 і 5 * 4', 'одиночні зірочки в тексті не чіпає');
ok(c('a_b_c і snake_case_name') === 'a_b_c і snake_case_name', 'підкреслення в словах не чіпає');
ok(c('Лови: ```\n**raw** <b>\n``` кінець **ок**') === 'Лови: <pre>**raw** &lt;b&gt;</pre> кінець ок', 'код лишається як є, поза кодом прибрано');
ok(c('') === '' && c(null) === null, 'порожнє безпечне');
console.log('\nПідсумок: ' + pass + ' ✔, ' + fail + ' ✘'); process.exit(fail ? 1 : 0);
