'use strict';
// Тести кошика кількох різних товарів (B4, 15.10, власник: «кошик кількох товарів — у пріоритет і закінчи»).
//   node scripts/qa/tests-basket-2026-10-15.js   → створює/оновлює тести, друкує id через пробіл
// Прогін з робочої копії гілки: BASKET_V1_FORCE=1 node scripts/qa/run-all-funnel-tests.js --only <id…>
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '..', '.env') });
const API = path.join(__dirname, '..', '..', 'apps', 'api', 'src', 'services');
const { db } = require(path.join(API, 'shopAgent/lib'));
const FT = require(path.join(API, 'funnelTests'));
const BOT = 'fcdee415-bef2-4a74-a650-e6e4b5a12322';

async function ensureTest(name, steps, expectedOutcome) {
    const ex = await db.funnelTest.findFirst({ where: { botId: BOT, name } });
    if (ex) { await db.funnelTest.update({ where: { id: ex.id }, data: { steps, expectedOutcome } }); return ex.id; }
    return (await FT.createTest({ botId: BOT, name, steps, expectedOutcome, createdBy: 'claude' })).id;
}
const t = (text) => ({ type: 'text', text });
const NOTE = ' (Поки бот веде інший товар, головний лежить у basket.anchor, готові позиції — у basket.lines; це НЕ втрата.)';

(async () => {
    const ids = [];
    ids.push(await ensureTest('15.10 К1. Кошик: два товари в першому повідомленні — «кофту A0187 і джинси»',
        [t('Хочу кофту A0187 і джинси'), t('180 80'), t('Кофта чорна'), t('Джинси сині')],
        'Клієнт одразу хоче два товари. Бот веде їх по черзі: спершу кофта A0187 (розмір за 180/80, колір чорний), потім джинси (розмір за ті ж 180/80 — вдруге зріст і вагу НЕ питає; колір синій). Наприкінці — підсумок з ОБОМА позиціями (кофта чорна, джинси сині, кожна з розміром і ціною) і сумою. Нічого не губиться.' + NOTE));
    ids.push(await ensureTest('15.10 К2. Кошик: відмова від одного товару посеред підбору — «ні, джинси не треба»',
        [t('Хочу кофту A0187'), t('180 80, чорна'), t('і ще джинси і футболку білу'), t('Ні, джинси не треба')],
        'Кофта A0187 (чорна, за 180/80) підібрана. Клієнт додає джинси й білу футболку, бот починає підбирати джинси; клієнт каже «джинси не треба» — бот прибирає ЛИШЕ джинси (не скасовує все замовлення, не каже «без тиску»), переходить до футболки (біла, розмір за 180/80) і показує підсумок: кофта + футболка, без джинсів, з правильною сумою.' + NOTE));
    ids.push(await ensureTest('15.10 К3. Кошик: дві кофти різних кольорів + футболка — «дві кофти A0187 чорну і сіру і ще футболку білу»',
        [t('Хочу дві кофти A0187 — чорну і світло-сіру, і ще футболку білу'), t('180 80')],
        'Клієнт хоче 2 кофти A0187 (чорна і світло-сіра) і білу футболку. Після «180 80» бот підбирає розмір (один для обох кофт), фіксує обидва кольори кофт (2 шт, ціна кофт — за акцією «2 шт», якщо вона є) і футболку (біла, розмір за 180/80). Підсумок містить кофти ×2 (чорна + світло-сіра) і футболку, сума правильна. Кольори вдруге не питає.' + NOTE));
    ids.push(await ensureTest('15.10 К4. Кошик до оплати: кофта + джинси → «Оформляємо» → «1» — сума до сплати включає обидва товари',
        [t('Хочу кофту A0187 і джинси'), t('180 80'), t('Кофта чорна'), t('Джинси сині'), t('Так, оформляємо'), t('1')],
        'Бот веде кофту і джинси по черзі (розмір за 180/80, кольори чорна/сині), показує підсумок з обома позиціями, на «Так, оформляємо» пропонує способи оплати, на «1» дає передоплату 200 грн і пише, що решта при отриманні = (ціна кофти + ціна джинсів − 200) грн. Сума рахує ОБИДВА товари; жоден не губиться між підсумком і оплатою.' + NOTE));
    console.log(ids.join(' '));
    process.exit(0);
})().catch((e) => { console.error(e.stack); process.exit(1); });
